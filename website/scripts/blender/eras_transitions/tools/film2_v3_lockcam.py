def prepare(a, b):
    """film.py's order maps, unchanged (the wipe grammar for everything that is not staged)"""
    d = np.abs(a['bimg'] - b['bimg']).max(-1) > 10
    if a['mask'] is not None: d &= nd.binary_dilation(a['mask'], iterations=6)
    d = nd.binary_closing(nd.binary_opening(d, iterations=1), iterations=3)
    lab, n = nd.label(d); O = np.full((H, W), 0.5, np.float32); Wd = np.ones((H, W), np.float32); OFF = np.zeros((H, W), np.float32)
    ga = np.where(solid(a), a['gid'] + 1, 0); gb = np.where(solid(b), b['gid'] + 1, 0)
    ha, hb = colh(ga), colh(gb); kinds = {}
    for c, sl in enumerate(nd.find_objects(lab)):
        m = lab[sl] == c + 1; A_, B_ = a['cls'][sl][m], b['cls'][sl][m]; n_ = m.sum()
        sa, sb = solid(a)[sl][m], solid(b)[sl][m]
        gain, loss = (sb & ~sa).mean() + (sb & sa & (hb[sl][m] > ha[sl][m] + 2)).mean(), (sa & ~sb).mean()
        st_new, st_gone = ((B_ == 2) & (A_ != 2)).mean(), ((A_ == 2) & (B_ != 2)).mean()
        wat = ((A_ == 4) != (B_ == 4)).mean(); tree = ((A_ == 3) | (B_ == 3)).mean(); car = ((A_ == 7) | (B_ == 7)).mean()
        k = ('rise' if gain > 0.25 and gain >= loss else 'sink' if loss > 0.25 else 'line' if max(st_new, st_gone) > 0.3 and n_ > 300
             else 'shore' if wat > 0.3 else 'grow' if tree > 0.4 else 'fade')
        kinds[k] = kinds.get(k, 0) + 1
        o = np.full(m.shape, 0.55, np.float32); w = np.full(m.shape, 0.7, np.float32)
        if k == 'rise':
            sel = solid(b)[sl] & m; hh = hb[sl]; mx = max(hh[sel].max() if sel.any() else 1, 1)
            o[sel] = 0.05 + 0.88 * hh[sel] / mx; w[sel] = 0.05; o[m & ~sel] = 0.9
        elif k == 'sink':
            sel = solid(a)[sl] & m; hh = ha[sl]; mx = max(hh[sel].max() if sel.any() else 1, 1)
            o[sel] = 0.93 - 0.88 * hh[sel] / mx; w[sel] = 0.05; o[m & ~sel] = 0.15
        elif k == 'line':
            py, px = ys[sl][m].astype(np.float32), xs[sl][m].astype(np.float32); cy, cx = py.mean(), px.mean()
            ev = np.linalg.eigh(np.cov(np.stack([px - cx, py - cy])))[1][:, -1]
            s = (xs[sl] - cx) * ev[0] + (ys[sl] - cy) * ev[1]; s = (s - s[m].min()) / max(np.ptp(s[m]), 1)
            if st_gone > st_new: s = 1 - s
            o = (0.04 + 0.9 * s).astype(np.float32); w[:] = 0.06
        elif k == 'shore':
            ref = ~m & (a['cls'][sl] != 4); dt = nd.distance_transform_edt(~ref); mx = max(dt[m].max(), 1)
            back = ((B_ == 4) & (A_ != 4)).mean() > ((A_ == 4) & (B_ != 4)).mean()
            o = (0.04 + 0.9 * (1 - dt / mx if back else dt / mx)).astype(np.float32); w[:] = 0.06
        elif k == 'grow':
            hh = (ys[sl].max() - ys[sl]).astype(np.float32); mx = max(np.ptp(ys[sl][m]), 1)
            o = (0.1 + 0.8 * (hh - hh[m].min()) / mx).astype(np.float32); w[:] = 0.25
        else:
            o[:] = 0.5 if car < 0.3 else 0.35; w[:] = 0.8
        O[sl][m], Wd[sl][m] = o[m], w[m]
        u = ((xs[sl][m].mean() * 73856093 + ys[sl][m].mean() * 19349663) % 1000) / 1000.0
        OFF[sl][m] = 0.15 * u
    return dict(O=O, Wd=Wd, OFF=OFF, mask=d, share=float(d.mean()), kinds=kinds)


