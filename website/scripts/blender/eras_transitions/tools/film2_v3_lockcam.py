def colh(g):
    """height in px of each pixel of a solid above its column's base (film.py)"""
    h = np.zeros(g.shape, np.float32); m = g > 0
    if not m.any(): return h
    rr, cc = np.nonzero(m); key = g[m].astype(np.int64) * g.shape[1] + cc
    uk, inv = np.unique(key, return_inverse=True); base = np.full(len(uk), -1, np.int64); np.maximum.at(base, inv, rr)
    h[rr, cc] = (base[inv] - rr).astype(np.float32)
    return h


