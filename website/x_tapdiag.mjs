import { chromium, devices } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], locale: 'en-US' });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message.slice(0, 200)));
await p.goto('http://localhost:3000/us/city/sf/the-city', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('.fx-city-controls', { timeout: 90000 });
await p.waitForTimeout(2000);
await p.getByRole('button', { name: 'District', exact: true }).tap();
await p.waitForTimeout(1500);
await p.evaluate(() => { window.__ev = []; const m = window.__cityTiles.map; for (const k of ['click', 'preclick', 'mousedown', 'mouseup', 'dragstart', 'movestart']) m.on(k, () => window.__ev.push(k)); });
const box = await p.locator('.fx-city-tiles').boundingBox();
const x = box.width * 0.55, y = box.height * 0.5;
console.log('pickAt', await p.evaluate(([x, y]) => window.__cityTiles.pickAt(x, y), [x, y]));
await p.touchscreen.tap(box.x + x, box.y + y);
await p.waitForTimeout(1200);
console.log('after touch tap: events', JSON.stringify(await p.evaluate(() => window.__ev)), 'ledger', await p.locator('.fx-city-ledger').count());
await p.evaluate(() => { window.__ev = []; });
await p.mouse.click(box.x + x, box.y + y);
await p.waitForTimeout(1500);
console.log('after mouse click: events', JSON.stringify(await p.evaluate(() => window.__ev)), 'ledger', await p.locator('.fx-city-ledger').count());
console.log('errors', errs.length ? errs : 'none');
await b.close();
