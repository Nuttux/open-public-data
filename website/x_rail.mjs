import { chromium, devices } from 'playwright';
const SCR = process.env.SCR;
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], locale: 'en-US' });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message.slice(0, 200)));
await p.goto('http://localhost:3000/us/city/sf/the-city', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('.fx-city-controls', { timeout: 90000 });
await p.waitForSelector('.fx-city-scrub', { timeout: 20000 });
await p.waitForTimeout(1500);
const st0 = await p.evaluate(() => { const q = (s) => document.querySelector(s); return { stage: q('.fx-city-stage') && Math.round(q('.fx-city-stage').getBoundingClientRect().height), clock: q('.fx-city-clockrow') && Math.round(q('.fx-city-clockrow').getBoundingClientRect().height), scrubs: document.querySelectorAll('.fx-city-scrub').length, readout: q('.fx-city-year')?.textContent ?? null }; });
console.log('before', JSON.stringify(st0));
await p.evaluate(() => { const el = document.querySelector('.fx-city-scrub'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, '1950'); el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); });
await p.waitForTimeout(2500);
const st1 = await p.evaluate(() => ({ readout: document.querySelector('.fx-city-year').textContent, tileUrls: [...new Set([...document.querySelectorAll('.fx-city-tile')].filter((i) => i.src).map((i) => i.src.replace(/.*city\//, '').split('/')[0]))], ovYear: window.__cityGLOverlay?.year, layers: document.querySelectorAll('.leaflet-tile-container').length }));
console.log('after 1950', JSON.stringify(st1));
await p.screenshot({ path: `${SCR}/m-rail-1950.png` });
console.log('errors', errs.length ? errs : 'none');
await b.close();
