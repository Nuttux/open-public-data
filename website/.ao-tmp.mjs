import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
const OUT = process.argv[2];
const b = await chromium.launch({ args:['--enable-unsafe-webgpu','--enable-features=Vulkan,WebGPU'] });
const p = await b.newPage({ viewport:{width:1440,height:900}, deviceScaleFactor:1 });
p.setDefaultTimeout(60000);
p.on('pageerror', e => console.log('PAGEERR', String(e).slice(0,300)));
p.on('console', m => { const t=m.text(); if (m.type()==='error'||/citygl/.test(t)) console.log(m.type().toUpperCase(), t.slice(0,220)); });
await p.goto('http://localhost:3000/us/city/sf/the-city-gl', { waitUntil:'domcontentloaded' });
await p.waitForFunction(() => !!globalThis.__cityGL, null, {timeout:180000});
await p.waitForTimeout(18000);
console.log('postOn', await p.evaluate(() => globalThis.__cityGL.postOn));
await p.evaluate(()=>{const e=globalThis.__cityGL,pr=globalThis.__cityGLProj;e.setStep(2);
  const c0=[3256,3339];const c=pr.proj(c0[0],c0[1],0);
  const a=pr.proj(c0[0]+1400,c0[1],0)[0]-pr.proj(c0[0],c0[1],0)[0];
  e.setCamera({cx:c[0],cy:c[1],scale:(e.viewport.W*0.94)/Math.abs(a)});});
await p.waitForTimeout(2500);
const grab = async (n) => { const d = await p.evaluate(async () => { const e=globalThis.__cityGL;
  await new Promise(r=>requestAnimationFrame(()=>{e.invalidate();requestAnimationFrame(r);}));
  const gpu=document.querySelector('.fx-city-canvas'); return gpu.toDataURL('image/png');});
  writeFileSync(`${OUT}/${n}.png`, Buffer.from(d.split(',')[1],'base64')); };
await grab('ao-on');
console.log('ON', await p.evaluate(()=>JSON.stringify(globalThis.__cityGL.getStats())));
await p.evaluate(()=>{globalThis.__cityGL.setPost(false);});
await p.waitForTimeout(2000);
await grab('ao-off');
console.log('OFF', await p.evaluate(()=>JSON.stringify(globalThis.__cityGL.getStats())));
await b.close();
